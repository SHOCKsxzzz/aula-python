lista = [2,3,3,5,6,6,7,7,8,9,10,11,7,6,3,2]
print(f"Quantidade de Elementos: {len(lista)}")
print(f"Existe o numero {3 in lista}")
print(f"Quantas vezes o numero aparece {lista.count(3)}")
print(f"Soma de todos os elementos da lista: {sum(lista)}")
print(f"Maior elemento da lista: {max(lista)}")
print(f"Menor elemento da lista: {min(lista)}")
print(f"Nova lista ordenada: {sorted(lista)}")